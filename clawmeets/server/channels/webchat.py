"""
clawmeets/server/channels/webchat.py
The web chat widget: a channel with no provider behind it.

A website embeds ``<script src="{server}/api/channels/widget.js"
data-key="cmw_…">``; its visitors chat with the agent, and each visitor's
conversation is a Front Desk thread like any Telegram or WhatsApp chat — the
same dedupe, burst buffer, rate limits, pause, owner takeover and outbox.

**Grants.** A connection has one or more grants (``store.webchat_grants``),
each an API key plus the site origins allowed to use it. The key is public by
design (it is in the host page's source); what it buys a caller is bounded by
the origin check, the gateway's rate limits and the message size cap. The
origin check stops other websites from embedding the widget — a browser sets
``Origin`` and a page cannot change it — but NOT a script or ``curl``, which
can send any ``Origin``. Revoking the grant, or disabling the connection, is
how the owner shuts a key off.

Turning the widget on creates one key whose only allowed site is this server
(``CLAWMEETS_SERVER_URL``); the owner adds their own sites to it. The server's
own pages — the hosted chat at ``/users/{username}/agents/{agent}/chat`` and the
account page — use the oldest key that lists this server
(``ChannelGateway.hosted_grant``). Taking the server off every key makes the
agent private.

**Visitors.** ``POST /api/channels/webchat/session`` mints a visitor id and a
visitor token: an HMAC, under the connection's own signing key (its stored
credential, generated by the server at connect), of the grant id and the
visitor id. Every later call carries both, so nobody can read or write another
visitor's conversation by guessing ids, and a visitor of one grant is not one
of another. Visitors are "verified by the provider" for the access rules
(``AUTH_PROVIDER``); widget connections start in "anyone" mode, since there is
no identity to put on an allowlist.

**Inbound.** The route checks the grant and the origin, then hands the
gateway a canonical JSON body it builds itself (never the visitor's bytes);
``verify`` checks the same things again under the gateway's usual order
(connection row, credential, disabled).

**Outbound.** ``send`` cannot call anyone: it writes the reply into the
visitor's mailbox (``store.webchat_messages``, once per retry key) and wakes
that visitor's open stream. The widget reads the mailbox by sequence number,
so a reconnecting stream resumes where it stopped.
"""
from __future__ import annotations

import asyncio
import base64
import hashlib
import hmac
import json
import re
import secrets
import time
from typing import Mapping, Optional, Sequence
from urllib.parse import urlsplit

from pydantic import SecretStr

from . import access
from .adapter import AdapterError, InboundEvent
from .store import ChannelConnection, ChannelStore, WebchatGrant

CHANNEL = "webchat"
KEY_PREFIX = "cmw_"
#: The only kind written; the ``kind`` column is otherwise unused.
GRANT_SITE = "site"

#: One visitor message, in characters. The route answers 413 past it.
MAX_TEXT_CHARS = 4000
MAX_LABEL_CHARS = 100
MAX_ORIGINS = 20

_VISITOR_RE = re.compile(r"^v_[A-Za-z0-9_-]{16,40}$")
_CLIENT_ID_RE = re.compile(r"^[A-Za-z0-9_-]{8,64}$")
_DEFAULT_PORTS = {"http": 80, "https": 443}


class OriginError(ValueError):
    """An allowed-site entry the owner typed is not an origin."""


def normalize_origin(raw: str) -> str:
    """``https://Acme.com/`` → ``https://acme.com``: scheme, host and a
    non-default port, nothing else. Raises :class:`OriginError`."""
    value = raw.strip().rstrip("/")
    try:
        parts = urlsplit(value)
        host = (parts.hostname or "").lower()
        port = parts.port
    except ValueError:
        raise OriginError(f"{raw!r} is not a URL") from None
    if parts.scheme not in ("http", "https") or not host:
        raise OriginError(f"{raw!r} must start with https:// (or http:// for local testing)")
    if parts.path or parts.query or parts.fragment or parts.username or parts.password:
        raise OriginError(f"{raw!r} must be a site origin only, e.g. https://acme.com")
    if ":" in host:
        host = f"[{host}]"
    if port is not None and port != _DEFAULT_PORTS[parts.scheme]:
        return f"{parts.scheme}://{host}:{port}"
    return f"{parts.scheme}://{host}"


def normalize_origins(values: Sequence[str]) -> list[str]:
    """Each entry normalised, duplicates dropped, order kept."""
    out: list[str] = []
    for value in values:
        if not value.strip():
            continue
        origin = normalize_origin(value)
        if origin not in out:
            out.append(origin)
    if len(out) > MAX_ORIGINS:
        raise OriginError(f"at most {MAX_ORIGINS} sites per key")
    return out


def new_grant_key() -> str:
    return KEY_PREFIX + secrets.token_urlsafe(24)


def new_signing_key() -> str:
    """The connection's credential: signs visitor tokens; never leaves the server."""
    return secrets.token_urlsafe(32)


def key_hash(key: str) -> str:
    return hashlib.sha256(key.strip().encode("utf-8")).hexdigest()


def new_visitor_id() -> str:
    return "v_" + secrets.token_urlsafe(18)


def visitor_token(signing_key: str, grant_id: str, visitor_id: str) -> str:
    mac = hmac.new(
        signing_key.encode("utf-8"), f"{grant_id}:{visitor_id}".encode("utf-8"), hashlib.sha256,
    ).digest()
    return base64.urlsafe_b64encode(mac).decode("ascii").rstrip("=")


def check_visitor(signing_key: str, grant_id: str, visitor_id: str, token: str) -> bool:
    if not _VISITOR_RE.match(visitor_id or "") or not token:
        return False
    return hmac.compare_digest(visitor_token(signing_key, grant_id, visitor_id), token)


def valid_client_id(value: str) -> bool:
    return bool(_CLIENT_ID_RE.match(value or ""))


def origin_allowed(grant: WebchatGrant, origin: Optional[str]) -> bool:
    if not origin:
        return False
    try:
        return normalize_origin(origin) in grant.origins
    except OriginError:
        return False


def visitor_name(visitor_id: str, origin: str) -> str:
    """What the owner sees for a visitor: no name is asked for, so the
    visitor's short id and the site they came from."""
    host = urlsplit(origin).hostname or "web"
    return f"Web visitor {visitor_id[2:6]} ({host})"


class WebChatAdapter:
    channel = CHANNEL
    #: No entry kind an owner could type: visitors have no identity worth
    #: allowlisting; an Allow on a Request still pins the visitor id.
    allowlist_kinds = (access.USER_ID,)
    provider_authenticates_sender = True
    #: The gateway mints the credential (a signing key) instead of asking for one.
    server_generated_secret = True
    #: Mode a new connection starts in.
    default_mode = access.MODE_ANYONE

    def __init__(self) -> None:
        self._store: Optional[ChannelStore] = None
        #: (connection, visitor) → the open streams' wake-up events.
        self._waiters: dict[tuple[str, str], set[asyncio.Event]] = {}

    def bind(self, *, store, config) -> None:
        self._store = store

    # ── inbound ──────────────────────────────────────────────────────────

    def verify(
        self, connection: ChannelConnection, secret: SecretStr,
        headers: Mapping[str, str], body: bytes, *, webhook_keys: Sequence[str] = (),
    ) -> Optional[int]:
        try:
            data = json.loads(body)
            grant = self._store.grant_by_key_hash(key_hash(data["key"]))
        except (ValueError, KeyError, TypeError, AttributeError):
            return None
        if grant is None or grant.connection_id != connection.id:
            return None
        origin = headers.get("origin")
        if not origin_allowed(grant, origin) or data.get("origin") != normalize_origin(origin):
            return None
        if not check_visitor(secret.get_secret_value(), grant.id,
                             data.get("visitor", ""), data.get("token", "")):
            return None
        return 0

    def parse(self, body: bytes) -> list[InboundEvent]:
        data = json.loads(body)
        visitor, text = data["visitor"], data["text"]
        if not isinstance(text, str) or not text.strip():
            return []
        return [InboundEvent(
            event_id=f"{visitor}:{data['id']}",
            conversation_key=visitor,
            user_key=visitor,
            display_name=visitor_name(visitor, data["origin"]),
            text=text,
            auth_verdict=access.AUTH_PROVIDER,
        )]

    # ── outbound ─────────────────────────────────────────────────────────

    def format_parts(self, text: str) -> list[str]:
        """Markdown as written: the widget renders it itself, as DOM nodes (never raw HTML)."""
        return [text] if text.strip() else []

    async def send(
        self, connection: ChannelConnection, secret: SecretStr, *,
        conversation_key: str, text: str, retry_key: str,
    ) -> None:
        if self._store is None:
            raise AdapterError("not_bound")
        self._store.webchat_post(
            connection_id=connection.id, visitor_id=conversation_key, text=text,
            retry_key=retry_key, now=time.time(),
        )
        self.wake(connection.id, conversation_key)

    # ── the visitor's stream ─────────────────────────────────────────────

    def wake(self, connection_id: str, visitor_id: str) -> None:
        for event in self._waiters.get((connection_id, visitor_id), ()):
            event.set()

    async def wait(self, connection_id: str, visitor_id: str, timeout: float) -> None:
        """Return when a reply is posted for this visitor, or after ``timeout``."""
        key = (connection_id, visitor_id)
        event = asyncio.Event()
        self._waiters.setdefault(key, set()).add(event)
        try:
            await asyncio.wait_for(event.wait(), timeout)
        except asyncio.TimeoutError:
            pass
        finally:
            waiters = self._waiters.get(key)
            if waiters is not None:
                waiters.discard(event)
                if not waiters:
                    self._waiters.pop(key, None)
